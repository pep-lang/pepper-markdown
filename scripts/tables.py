"""Writes tables.pep: HTML's named character references, Unicode case
folding, and Unicode punctuation, as the parser looks them up.

Usage: python scripts/tables.py entities.json tables.pep

entities.json is https://html.spec.whatwg.org/entities.json; the Unicode
data is Python's unicodedata, so a newer Python gives a newer Unicode.
"""
import json
import sys
import unicodedata

NL = '\\n'  # a "\n" escape in the Pepper string, not a line ending

entities = json.load(open(sys.argv[1], encoding='utf-8'))
names = sorted(name[1:-1] for name in entities if name.endswith(';'))
entity_table = ''.join(
    NL + '%s:%s' % (name, ','.join('%X' % c for c in entities['&' + name + ';']['codepoints']))
    for name in names) + NL

folds = []
for point in range(0x80, 0x110000):
    if 0xD800 <= point < 0xE000:
        continue
    folded = chr(point).casefold()
    if folded != chr(point):
        folds.append('%X:%s' % (point, ','.join('%X' % ord(c) for c in folded)))
fold_table = NL + NL.join(folds) + NL

ranges = []
start = None
for point in range(0x80, 0x110001):
    punctuation = point < 0x110000 and unicodedata.category(chr(point))[0] in 'PS'
    if punctuation and start is None:
        start = point
    if not punctuation and start is not None:
        ranges.append('%X-%X' % (start, point - 1))
        start = None
punctuation_table = ',' + ','.join(ranges) + ','

TEMPLATE = '''## Tables the parser looks things up in: HTML's named character
## references, Unicode case folding, and Unicode punctuation. Generated by
## `scripts/tables.py` from the WHATWG `entities.json` and Python's
## `unicodedata` (Unicode %s).

# format: off

# Each named reference (without its `&` and `;`) as `\\nname:code points`,
# the code points in hexadecimal, separated by `,`.
const _ENTITIES = "%s";

# Each non-ASCII code point whose full case folding differs from itself, as
# `\\ncode point:folded code points`, in hexadecimal.
const _CASE_FOLDING = "%s";

# The non-ASCII ranges of Unicode punctuation (general category P) and
# symbols (S), as `,first-last`, in hexadecimal and in order.
const _PUNCTUATION = "%s";

# format: on
'''

with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as out:
    out.write(TEMPLATE % (unicodedata.unidata_version, entity_table, fold_table, punctuation_table))
